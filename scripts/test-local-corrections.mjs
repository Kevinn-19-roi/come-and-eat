import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ExcelJS from 'exceljs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const migration = read('supabase/migrations/202610130001_statistics_periods.sql');
const settings = read('src/app/admin/settings/page.tsx');
const dashboard = read('src/services/admin-dashboard.ts');
const usersExport = read('src/app/admin/users/export/route.ts');
const usersExportMigration = read('supabase/migrations/202610130002_admin_user_export_activity.sql');
const restaurantPage = read('src/app/(public)/restaurants/[slug]/page.tsx');
const upload = read('src/services/media-upload.ts');
const email = read('src/lib/notifications/templates.ts');

assert.match(migration, /statistics_periods/);
assert.doesNotMatch(migration, /delete\s+from\s+public\.orders/i);
assert.doesNotMatch(migration, /'-infinity'/);
assert.match(migration, /admin_statistics_summary/);
assert.match(migration, /payment_status = 'paid'/);
assert.match(settings, /Démarrer une nouvelle période statistique/);
assert.match(dashboard, /statistics_periods/);
assert.match(usersExport, /application\/vnd\.openxmlformats-officedocument\.spreadsheetml\.sheet/);
assert.match(usersExport, /requireAdmin/);
assert.match(usersExport, /admin_export_users/);
assert.doesNotMatch(usersExport, /password|token|identity_number/i);
assert.match(usersExportMigration, /public\.is_admin\(\)/);
assert.match(usersExportMigration, /last_sign_in_at/);
assert.match(usersExportMigration, /revoke all.+public, anon/is);
assert.match(restaurantPage, /Écrire sur WhatsApp/);
assert.match(restaurantPage, /mailto:/);
assert.match(upload, /HEIC\/HEIF/);
assert.match(email, /https:\/\/comeandeat\.org|NEXT_PUBLIC_SITE_URL/);
assert.match(email, /come-eat-email-logo\.png/);
const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet('Utilisateurs');
sheet.columns = [{ header: 'Nom et prénom', key: 'name', width: 30 }];
for (let index = 0; index < 5_000; index += 1) sheet.addRow({ name: `Élodie Koné ${index}` });
const xlsx = await workbook.xlsx.writeBuffer();
const reopened = new ExcelJS.Workbook();
await reopened.xlsx.load(xlsx);
assert.equal(reopened.getWorksheet('Utilisateurs')?.getCell('A2').value, 'Élodie Koné 0');
assert.equal(reopened.getWorksheet('Utilisateurs')?.rowCount, 5_001);
console.log('Local correction checks passed.');
