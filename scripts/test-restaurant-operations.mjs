const checkout=read('src/app/(public)/checkout/actions.ts');
assert.ok(checkout.includes('ensureRestaurantsCanOrder'));
assert.ok(checkout.includes('get_restaurant_ordering_statuses'));
const whatsapp=await import('../src/lib/whatsapp.ts');
assert.equal(whatsapp.normalizeWhatsAppNumber('+225 07 11 45 97 23'),'2250711459723');
assert.equal(whatsapp.normalizeWhatsAppNumber('07-11-45-97-23'),'2250711459723');
const link=whatsapp.buildRestaurantOrderWhatsAppLink({number:'+225 07 11 45 97 23',restaurantName:'Chez A',reference:'CE-TEST',customerName:'Kevin',customerPhone:'+225 01',fulfillment:'delivery',zone:'Cocody',address:'Riviera',instructions:'Portail bleu',items:[{quantity:2,product_name:'Burger',options:[{name:'Frites'}]}],amount:12500,paymentStatus:'paid'});
