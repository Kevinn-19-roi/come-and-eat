const message=decodeURIComponent(link.split('?text=')[1]);
for(const marker of ['Chez A','CE-TEST','2x Burger','Frites','12 500','Paiement vérifié'])assert.ok(message.includes(marker),`Message WhatsApp incomplet: ${marker}`);
assert.ok(!message.includes('Restaurant B'));
