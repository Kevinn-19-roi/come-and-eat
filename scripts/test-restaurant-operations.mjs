import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>fs.readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const sql=read('supabase/migrations/202608240003_enforce_restaurant_ordering.sql');
const paymentsSql=read('supabase/migrations/202608230001_secure_payments_checkout.sql');
